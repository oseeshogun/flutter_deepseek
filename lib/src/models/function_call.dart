/// JSON-schema function definition for tool calling.
class FunctionDefinition {
  /// Creates a function definition.
  const FunctionDefinition({
    required this.name,
    required this.description,
    required this.parameters,
  });

  /// Parses a function definition from JSON.
  factory FunctionDefinition.fromJson(Map<String, dynamic> json) {
    return FunctionDefinition(
      name: json['name'] as String? ?? '',
      description: json['description'] as String? ?? '',
      parameters: (json['parameters'] as Map<String, dynamic>?) ?? {},
    );
  }

  /// Function name the model may call.
  final String name;

  /// Human-readable description for the model.
  final String description;

  /// JSON Schema object describing parameters.
  final Map<String, dynamic> parameters;

  /// Serializes to JSON for the tools array.
  Map<String, dynamic> toJson() => {
        'name': name,
        'description': description,
        'parameters': parameters,
      };
}

/// A tool entry in the chat completions `tools` list.
class DeepSeekTool {
  /// Creates a function tool.
  const DeepSeekTool({
    this.type = 'function',
    required this.function,
  });

  /// Parses a tool from JSON.
  factory DeepSeekTool.fromJson(Map<String, dynamic> json) {
    return DeepSeekTool(
      type: json['type'] as String? ?? 'function',
      function: FunctionDefinition.fromJson(
        json['function'] as Map<String, dynamic>? ?? {},
      ),
    );
  }

  /// Tool type; always `function` for DeepSeek today.
  final String type;

  /// Function metadata and parameter schema.
  final FunctionDefinition function;

  /// Serializes to JSON.
  Map<String, dynamic> toJson() => {
        'type': type,
        'function': function.toJson(),
      };
}

/// Function name and arguments emitted by the model.
class FunctionCall {
  /// Creates a function call payload.
  const FunctionCall({
    required this.name,
    required this.arguments,
  });

  /// Parses from JSON.
  factory FunctionCall.fromJson(Map<String, dynamic> json) {
    return FunctionCall(
      name: json['name'] as String? ?? '',
      arguments: json['arguments'] as String? ?? '',
    );
  }

  /// Name of the function to invoke.
  final String name;

  /// JSON string of arguments generated by the model.
  final String arguments;

  /// Serializes to JSON.
  Map<String, dynamic> toJson() => {
        'name': name,
        'arguments': arguments,
      };
}

/// A tool call item on an assistant message.
class ToolCall {
  /// Creates a tool call.
  const ToolCall({
    required this.id,
    required this.type,
    required this.function,
  });

  /// Parses from JSON.
  factory ToolCall.fromJson(Map<String, dynamic> json) {
    return ToolCall(
      id: json['id'] as String? ?? '',
      type: json['type'] as String? ?? 'function',
      function: FunctionCall.fromJson(
        json['function'] as Map<String, dynamic>? ?? {},
      ),
    );
  }

  /// Unique tool call id.
  final String id;

  /// Tool type, typically `function`.
  final String type;

  /// Function invocation details.
  final FunctionCall function;

  /// Serializes to JSON.
  Map<String, dynamic> toJson() => {
        'id': id,
        'type': type,
        'function': function.toJson(),
      };
}
